interface Case {
	name: string;
	build: () => string;
	expected?: string;
	contains?: string[];
	excludes?: string[];
}

/**
 * Extract the contents of the `:root { ... }` block from an `emit_app_context`
 * output so density-cascade assertions don't leak into the `.dark` block (which
 * intentionally inherits theme defaults regardless of `density`).
 * @param markdown - Full `buildAppContext` output
 * @returns The raw `:root { ... }` body, or empty string if no `:root` rule found
 */
function extractRootBlock(markdown: string): string {
	const start = markdown.indexOf("  :root {");
	if (start === -1) return "";
	const end = markdown.indexOf("  }", start);
	return end === -1 ? markdown.slice(start) : markdown.slice(start, end);
}

